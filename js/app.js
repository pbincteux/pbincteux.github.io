let aboutOpen = false
let workMenuOpen = false
let active = null
let mediaObserver = null

function encodeSrc(src) {
  return src
    .split('/')
    .map((part) => encodeURIComponent(part))
    .join('/')
}

function renderCopy(study) {
  if (!study) {
    copyTop.innerHTML = `<p class="intro">${introText}</p>`
    return
  }

  const roles = study.roles.join(' / ')
  const testimonial = study.testimonial
    ? `<div class="study-row">
        <span class="study-label">Testimonial</span>
        <figure class="testimonial">
          <img src="${encodeSrc(study.testimonial.photo)}" alt="${study.testimonial.name}" />
          <div>
            <blockquote>“${study.testimonial.quote}”</blockquote>
            <cite>${study.testimonial.name}<br />${study.testimonial.role}</cite>
          </div>
        </figure>
      </div>`
    : ''

  copyTop.innerHTML = `
    <div class="study">
      <div class="study-row">
        <span class="study-label">Organisation</span>
        <span>${study.organisation}</span>
      </div>
      <div class="study-row">
        <span class="study-label">My role</span>
        <span class="roles">${roles}</span>
      </div>
      <div class="study-row">
        <span class="study-label">Description</span>
        <p>${study.description}</p>
      </div>
      <div class="study-row">
        <span class="study-label">${study.impactLabel}</span>
        <p>${study.impact}</p>
      </div>
      ${testimonial}
    </div>
  `
}

function renderMedia(items) {
  const html = items
    .map((item) => {
      const src = encodeSrc(item.src)
      if (item.playButton) {
        const poster = encodeSrc(item.poster)
        return `<div class="media-item">
          <button
            type="button"
            class="video-poster"
            data-video-src="${src}"
            data-video-poster="${poster}"
            data-video-name="${item.name}"
            aria-label="Play ${item.name}"
          >
            <img src="${poster}" alt="" loading="lazy" />
            <span class="video-play-button" aria-hidden="true">
              <svg viewBox="0 0 24 24" focusable="false"><path d="M8 5.5v13l10-6.5z" /></svg>
            </span>
          </button>
        </div>`
      }

      if (item.type === 'video') {
        return `<div class="media-item"><video src="${src}" autoplay muted loop playsinline></video></div>`
      }
      return `<div class="media-item"><img src="${src}" alt="${item.name}" loading="lazy" /></div>`
    })
    .join('')

  mediaCol.innerHTML = `<div class="media-stack">${html}</div>`
  mediaCol.scrollTop = 0
  revealMediaItems()
}

function revealMediaItems() {
  const items = mediaCol.querySelectorAll('.media-item')
  if (mediaObserver) mediaObserver.disconnect()

  if (!('IntersectionObserver' in window)) {
    items.forEach((item) => item.classList.add('is-visible'))
    return
  }

  const root = window.matchMedia('(min-width: 768px)').matches ? mediaCol : null
  mediaObserver = new IntersectionObserver(
    (entries, currentObserver) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return
        entry.target.classList.add('is-visible')
        currentObserver.unobserve(entry.target)
      })
    },
    { root, threshold: 0.08, rootMargin: '0px 0px -4% 0px' },
  )

  items.forEach((item) => mediaObserver.observe(item))
}

function renderWorkNav() {
  workList.innerHTML = projects
    .map((project, i) => {
      const marker =
        active === i ? '<span class="dot"></span>' : `<span>${i + 1}</span>`
      return `
        <li>
          <span class="work-index">${marker}</span>
          <button type="button" data-index="${i}">${project.title}</button>
        </li>
      `
    })
    .join('')
}

function showHome() {
  active = null
  renderCopy()
  renderMedia(homeGallery)
  renderWorkNav()
}

function showProject(index) {
  const project = projects[index]
  if (!project?.study) return
  active = active === index ? null : index
  if (active === null) {
    showHome()
    return
  }
  renderCopy(project.study)
  renderMedia(project.study.gallery)
  renderWorkNav()
}

function setAbout(open) {
  if (open) setWorkMenu(false)
  aboutOpen = open
  app.classList.toggle('is-about-open', aboutOpen)
  if (window.matchMedia('(max-width: 767px)').matches) {
    app.classList.remove('is-about-hover')
  }
  aboutToggle.setAttribute('aria-expanded', String(aboutOpen))
  aboutToggle.setAttribute('aria-label', aboutOpen ? 'Close about' : 'Open about')
  aboutPanel.setAttribute('aria-hidden', String(!aboutOpen))
}

function setWorkMenu(open) {
  if (open && aboutOpen) setAbout(false)
  workMenuOpen = open
  app.classList.toggle('is-work-menu-open', workMenuOpen)
  workMenuToggle.setAttribute('aria-expanded', String(workMenuOpen))
  workMenuToggle.setAttribute(
    'aria-label',
    workMenuOpen ? 'Close selected work menu' : 'Open selected work menu',
  )
}

aboutToggle.addEventListener('click', () => setAbout(!aboutOpen))
aboutToggle.addEventListener('pointerenter', (event) => {
  if (event.pointerType === 'mouse') app.classList.add('is-about-hover')
})
aboutToggle.addEventListener('pointerleave', (event) => {
  if (event.pointerType === 'mouse') app.classList.remove('is-about-hover')
})
workMenuToggle.addEventListener('click', () => setWorkMenu(!workMenuOpen))
mobileAboutLink.addEventListener('click', () => {
  setWorkMenu(false)
  setAbout(true)
})
homeBtn.addEventListener('click', () => {
  setWorkMenu(false)
  showHome()
  if (window.matchMedia('(max-width: 767px)').matches) {
    window.scrollTo({ top: 0, behavior: 'smooth' })
  }
})
workList.addEventListener('click', (event) => {
  const button = event.target.closest('button[data-index]')
  if (!button) return
  setWorkMenu(false)
  showProject(Number(button.dataset.index))
  if (window.matchMedia('(max-width: 767px)').matches) {
    window.scrollTo({ top: 0, behavior: 'smooth' })
  }
})

document.addEventListener('keydown', (event) => {
  if (event.key !== 'Escape') return
  if (workMenuOpen) setWorkMenu(false)
  if (aboutOpen) setAbout(false)
})

mediaCol.addEventListener('click', (event) => {
  const button = event.target.closest('button.video-poster')
  if (!button) return

  const video = document.createElement('video')
  video.className = 'media-video'
  video.controls = true
  video.playsInline = true
  video.preload = 'metadata'
  video.poster = button.dataset.videoPoster
  video.src = button.dataset.videoSrc
  video.setAttribute('aria-label', button.dataset.videoName)
  button.replaceWith(video)

  const playRequest = video.play()
  if (playRequest) playRequest.catch(() => video.focus())
})

app.addEventListener(
  'wheel',
  (event) => {
    if (window.matchMedia('(max-width: 767px)').matches || event.ctrlKey) return
    if (app.classList.contains('is-about-open') && event.target.closest('.about-scroll')) return

    event.preventDefault()
    const multiplier = event.deltaMode === 1 ? 16 : event.deltaMode === 2 ? mediaCol.clientHeight : 1
    mediaCol.scrollTop += event.deltaY * multiplier
  },
  { passive: false },
)

setAbout(false)
showHome()
